// Emits src/data/associahedronInvariants.ts from public/models/associahedron.json.
// Run after every re-bake:  node scripts/gen-associahedron-invariants.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const doc = JSON.parse(readFileSync(resolve(root, 'public/models/associahedron.json'), 'utf8'));

const orders = doc.orders.map((o) => {
  const frames = o.frames
    .map((f) => `      { mesh: '${f.mesh}', V: ${f.V}, E: ${f.E}, F: ${f.F}, euler: ${f.euler} }`)
    .join(',\n');
  return `  ${o.order}: {
    order: ${o.order},
    combinatorialVertices: ${o.combinatorialVertices},
    coordinateSum: ${o.coordinateSum},
    ambientDim: ${o.ambientDim},
    affineDim: ${o.affineDim},
    projected: ${o.projected},
    isometryMaxError: ${o.isometryMaxError ?? 'null'},
    frames: [
${frames}
    ]
  }`;
}).join(',\n');

const out = `// GENERATED by scripts/gen-associahedron-invariants.mjs — do not edit by hand.
// Source of truth: public/models/associahedron.json (re-bake with the Blender generator).
// scripts/verify-associahedron.mjs re-derives the hull of every frame independently
// (Loday -> project -> ConvexHull) and fails if these numbers disagree with the GLB.

export interface AssociahedronFrame {
  mesh: string;
  V: number;
  E: number;
  F: number;
  euler: number;
}

export interface AssociahedronOrderData {
  order: number;
  combinatorialVertices: number;
  coordinateSum: number;
  ambientDim: number;
  affineDim: number;
  projected: boolean;
  isometryMaxError: number | null;
  frames: AssociahedronFrame[];
}

export const ASSOCIAHEDRON_GENERATOR = '${doc.generator}';
export const ASSOCIAHEDRON_BLENDER = '${doc.blenderVersion}';
export const ASSOCIAHEDRON_REALIZATION = '${doc.realization}';
export const ASSOCIAHEDRON_SWEEP_AMPLITUDE = ${doc.sweepAmplitudeRad};

export const ASSOCIAHEDRON_ORDERS: Record<number, AssociahedronOrderData> = {
${orders}
};

export const ASSOCIAHEDRON_ORDERS_LIST = [4, 5, 6] as const;

export function clampOrder(value: number): 4 | 5 | 6 {
  const n = Math.round(value);
  return (n <= 4 ? 4 : n >= 6 ? 6 : 5) as 4 | 5 | 6;
}

export function frameIndexFor(sweep: number, order: 4 | 5 | 6): number {
  const frames = ASSOCIAHEDRON_ORDERS[order].frames.length;
  if (frames <= 1) return 0;
  const t = Math.max(0, Math.min(1, sweep));
  return Math.min(frames - 1, Math.round(t * (frames - 1)));
}

export function invariantsFor(order: 4 | 5 | 6, sweep: number) {
  const data = ASSOCIAHEDRON_ORDERS[order];
  const frame = data.frames[frameIndexFor(sweep, order)];
  return { ...data, frame };
}
`;

writeFileSync(resolve(root, 'src/data/associahedronInvariants.ts'), out);
console.log('wrote src/data/associahedronInvariants.ts', out.length, 'bytes');
